#                                 --- INPUT ---
#Jadi dalam proses input pengguna memasukan nilai seperti nama,harga,jumlah dan
#nilai lain nya, di bagian ini data yang dimasukan ke dalam input akan disimpan
#ke dalam variabel agar bisa di panggil kembali dalam bagian pemrosesan

nama = input('Masukan nama :')                                                    #Memasukan nama pelanggan

#input barang pertama
barang_1    =  input('Masukan nama barang 1 :')
harga_1     =  int(input('Masukan harga barang 1 :'))                             #memasukan nama,harga, dan jumlah barang ke 1
jumlah_1    =  int(input('Masukan jumlah barang 1 :'))

#Input barang kedua
barang_2    =  input('Masukan nama barang 2 :')
harga_2     =  int(input('Masukan harga barang 2 :'))                             #memasukan nama,harga, dan jumlah barang ke 2
jumlah_2    =  int(input('Masukan jumlah barang 2 :'))

#Input barang ketiga
barang_3    =  input('Masukan nama barang 3 :')
harga_3     =  int(input('Masukan harga barang 3 :'))                             #memasukan nama,harga, dan jumlah barang ke 3
jumlah_3    =  int(input('Masukan jumlah barang 3 :'))


#                    --- PEMROSESAN ---
#Jadi di bagian pemerosesan data yang sudah dimasukan akan di proses menjadi
#subtotal, harga, total, dan nilai yang di butuhkan lainnya, nilai yang sudah
#diproses dimasukan ke dalam variabel agar bisa di panggil di bagian output

subtotal_1  = harga_1 * jumlah_1
subtotal_2  = harga_2 * jumlah_2                                                  #menghitung subtotal setiap barang
subtotal_3  = harga_3 * jumlah_3
total       = subtotal_1 + subtotal_2 + subtotal_3                                #menjumlahkan subtotal agar jadi total keseluruhan
diskon      = int(total * 0.1)                                                    #menghitung diskon 10% dari total keseluruhan
total_bayar = total - diskon                                                      #menghitung yang harus dibayar setelah diskon

while True:
  data = input('Masukan uang yang dibayar :')
  try:
    uang = int(data)
  except ValueError:
    print('HARUS ANGKA!!')                                                        #mengecek uang pelanggan
    continue
  if uang < 0:
    print('TIDAK BOLEH CASBON!!')
  elif uang < total_bayar:
    print('UANG KURANG!! :',total_bayar - uang)
  else:
    break

kembalian   = uang - total_bayar                                                  #menghitung kembalian
garis       = '='*60




#                   --- OUTPUT ---
#Bagian di mana kita menampilkan hasil data yang sudah melalui bagian pemrosesan
#di bagian ini data yang telah kita proses seperti nama,harga dan yang lain nya
#dipanggil kembali

print(f"""

{garis}

{'TOKO MAHASISWA':^60}

{garis}
Nama Pelanggan : {nama}

{'Barang':<25}{'Qty':^10}{'Subtotal':^26}
{'-'*60}

{barang_1:<25}{jumlah_1:^10}{'Rp ':>10}{subtotal_1:<19}

{barang_2:<25}{jumlah_2:^10}{'Rp ':>10}{subtotal_2:<19}

{barang_3:<25}{jumlah_3:^10}{'Rp ':>10}{subtotal_3:<19}

{'-'*60}

{'Total Belanja':<42}Rp {total}

{'Diskon 10%':<42}Rp {diskon}

{'Total Bayar':<42}Rp {total_bayar}

{'Uang Dibayar':<42}Rp {uang}

{'Kembalian':<42}Rp {kembalian}

{garis}

{'Terima Kasih':^60}

{garis}
""")