nilai = input('Masukan Nilai : ')
n_uts = input('Masukan Nilai UTS : ')
n_uas = input('Masukan Nilai UAS : ')

if nilai.isnumeric() and n_uts.isnumeric() and n_uas.isnumeric() :
  nilai = int(nilai)
  n_uts = int(n_uts)
  n_uas = int(n_uas)

  n_akhir = (nilai/10*3) + (n_uts/10*3) + (n_uas/10*4)

  if n_uas < 40 :
    print ('kamu tidak Lulus !! Karena nilai UAS di bawah 40 ')
  elif n_akhir >= 80 :
    print('Nilai mu A')
  elif n_akhir >= 70 :
    print('Nilai mu B')
  elif n_akhir >= 60 :
    print('Nilai mu C')
  elif n_akhir >= 50 :
    print('Nilai mu D')
  else :
    print('Nilai mu E')
else :
  print('Masukan angka nilai!!')

