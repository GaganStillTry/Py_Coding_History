umur = input('Masukan umur mu: ').strip()
if umur.isdigit() == False:
  print('Masukan angka ya!!')
elif umur.isdigit() == True :
  umur = int(umur)
  if umur <= 0 or umur >= 100 :
    print('Umur Tidak Valid !!')
  elif umur <= 10 :
    print('Kamu masih anak anak ')
  elif umur <= 20 :
    print('kamu masih remaja ')
  elif umur <= 50 :
    print('Kamu sudah Dewasa')
  elif umur <= 99 :
    print('Kamu sudah tua')
  else :
    print('masukan angka ya')